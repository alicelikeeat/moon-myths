/// 公式里用到的符号
func symbolsUsed(in formula: String) -> [(String, String, String)] {
    var seen = Set<String>()
    var matched: [String] = []
    return symbolGlossary.filter { item in
        guard formula.contains(item.0) else { return false }
        // “max”已经包含在“argmax”里时不重复列出
        if matched.contains(where: { $0 != item.0 && $0.contains(item.0) }) { return false }
        matched.append(item.0)
        // “⟹̸”与“⇏”意思相同，只列一次
        let key = item.1
        if seen.contains(key) { return false }
        seen.insert(key)
        return true
    }
}

/// 公式下方的“读法与解释”
struct FormulaExplainer: View {
    let formula: String
    @State private var open = false

    var body: some View {
        let note = formulaNotes[formula]
        let syms = symbolsUsed(in: formula)
        if note != nil || !syms.isEmpty {
            VStack(alignment: .leading, spacing: 8) {
                Button {
                    withAnimation(.snappy(duration: 0.25)) { open.toggle() }
                } label: {
                    Label(open ? "收起" : "公式动画 · 读法与解释", systemImage: open ? "chevron.up" : "function")
                        .font(.caption.weight(.semibold))
                }
                .buttonStyle(.glass)
                if open {
                    FormulaAnimationView(formula: formula, note: note)
                        .transition(.opacity.combined(with: .move(edge: .top)))
                }
            }
        }
    }
}
