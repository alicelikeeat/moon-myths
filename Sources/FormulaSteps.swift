/// 把片段对应到记号的下标（忽略空格比较）
func stepTokenRanges(_ tokens: [String], _ piece: String) -> [Int] {
    let target = piece.replacingOccurrences(of: " ", with: "")
    var flat = ""
    var owner: [Int] = []
    for (i, t) in tokens.enumerated() {
        let s = t.replacingOccurrences(of: " ", with: "")
        flat += s
        owner += Array(repeating: i, count: s.count)
    }
    guard let r = flat.range(of: target) else { return [] }
    let a = flat.distance(from: flat.startIndex, to: r.lowerBound)
    let b = flat.distance(from: flat.startIndex, to: r.upperBound)
    return Array(Set(owner[a..<b])).sorted()
}
